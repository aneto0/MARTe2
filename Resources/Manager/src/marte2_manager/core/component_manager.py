    def _expand_parameter_info_header_doc(self, parameter_name, parameter_info, prefix = ' * ', expand_description = True):
        default_value = parameter_info.get('default_value', None)
        parameter_type = parameter_info['type']
        if parameter_type == 'enum':
            enum_0_val = list(parameter_info['enum_values'].keys())[0]
            default_value = f'"{enum_0_val}"'

        if default_value is None:
            if parameter_type == 'StreamString':
                default_value = '""'
            else:
                default_value = '0' 

        number_of_elements = parameter_info.get('number_of_elements', 1) 
        if isinstance(number_of_elements, int):
            if number_of_elements > 1:
                if parameter_type == 'StreamString':
                    default_value = '{' + ' '.join(['" "'] * number_of_elements) + '}'
                else:
                    default_value = '{' + ' '.join(['0'] * number_of_elements) + '}'
        elif isinstance(number_of_elements, list):
            number_of_rows = number_of_elements[0]
            number_of_cols = number_of_elements[1]
            default_value = '{'
            for r in range(number_of_rows):
                default_value += '{' + ' '.join(['0'] * number_of_cols) + '}'
            default_value += '}'

        required_parameter = parameter_info.get('required', False)
        line  = f'\n{prefix}{self.TAB}{parameter_name} = {default_value}'
        if expand_description:
            line += ' //'
            if required_parameter:
                line += 'Required. '
            else:
                line += 'Optional. '

            if parameter_type == 'enum':
                line += f'Options: {", ".join(parameter_info["enum_values"].keys())}. '

            line += f'{parameter_info["description"]}'
        return line


    def _expand_parameter_info_header(self, parameter_name, parameter_info):
        description = parameter_info['description']
        parameter_type = parameter_info['type']
        if parameter_type == 'enum':
            parameter_type = parameter_info.get('enum_type', 'uint32')
        if not parameter_type.startswith('MARTe::'):
            parameter_type = f'MARTe::{parameter_type}'

        number_of_elements = parameter_info.get('number_of_elements', 1)
        
        if isinstance(number_of_elements, int):
            if number_of_elements > 1:
                parameter_type += ' *' 
            else:
                parameter_type += ' '
        elif isinstance(number_of_elements, list):
            parameter_type += ' **' 
        else:
            parameter_type += ' '
            logger.warning(f'Parameter {parameter_name} has an invalid number_of_elements: {number_of_elements}. Defaulting to 1.')

        parameter_name_lower_case = self._generate_lower_case_var(parameter_name)
        line  = f'\n{self.TAB}/**'
        line += f'\n{self.TAB} * {description}'
        line += f'\n{self.TAB} */'
        line += f'\n{self.TAB}{parameter_type}{parameter_name_lower_case};'
        line += '\n'

        if isinstance(number_of_elements, int):
            if number_of_elements > 1:
                line += f'{self.TAB}MARTe::uint32 nOfElements{parameter_name};'
        elif isinstance(number_of_elements, list):
            line += f'{self.TAB}MARTe::uint32 nOfRows{parameter_name};'
            line += f'\n{self.TAB}MARTe::uint32 nOfCols{parameter_name};\n'

        return line

