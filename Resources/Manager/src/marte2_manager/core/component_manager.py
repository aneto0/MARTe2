    def expand_from_template(self, template_dict):
        src_folder_name = self._app_def_data['folders']['src']['name']
        comp_type_name = self._app_def_data['components'][self._comp_type]['name']
        header_file_path = Path(self._project_path) / self._project_name / src_folder_name / comp_type_name / self._comp_name / f'{self._comp_name}.h'
