    def _generate_lower_case_var(self, name):
        ret = name
        match = re.match(r'^([A-Z]+)', name)
        if match:
            prefix = match.group(1)
            # If only one uppercase letter → lowercase it
            if len(prefix) == 1:
                new_prefix = prefix.lower()
            else:
                # Lowercase all but the last uppercase letter
                new_prefix = prefix[:-1].lower() + prefix[-1]
            ret = new_prefix + name[len(prefix):]
        return ret

    def _replace_autogenerated_section(self, filename, new_lines, autogenerated_start_marker, autogenerated_end_marker):
        ok = True
        with open(filename, 'r') as f:
            lines = f.readlines()

        start_idx = None
        end_idx = None

        # Find markers
        for i, line in enumerate(lines):
            if autogenerated_start_marker in line:
                start_idx = i
            elif autogenerated_end_marker in line:
                end_idx = i
                break  

        if start_idx is None or end_idx is None or start_idx >= end_idx:
            ok = False
            logger.critical(f'Markers not found or invalid in {filename}. Start idx: {start_idx}, End idx: {end_idx}, Start marker: {autogenerated_start_marker}, End marker: {autogenerated_end_marker}')

        if ok:
            updated_lines = (
                lines[:start_idx + 1] +   # keep start marker
                new_lines +               # insert new content
                lines[end_idx:]           # keep end marker + rest
            )

        # Write back
        if ok:
            with open(filename, 'w') as f:
                f.writelines(updated_lines)

        return ok

