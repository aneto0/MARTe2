    def _expand_parameter_info_constructor(self, parameter_name, parameter_info):
        parameter_name_lower_case = self._generate_lower_case_var(parameter_name)
        parameter_type = parameter_info['type']
        if parameter_type == 'enum':
            parameter_type = parameter_info.get('enum_type', 'uint32')

        line = f'\n{self.TAB}{parameter_name_lower_case}'

        number_of_elements = parameter_info.get('number_of_elements', 1)
        if isinstance(number_of_elements, int):
            if number_of_elements > 1:
                line += f' = NULL_PTR({parameter_type} *);'
            else:
                if 'int' in parameter_type:
                    line += ' = 0;'
                elif 'float' in parameter_type:
                    line += ' = 0.0f;'
                elif 'bool' in parameter_type:
                    line += ' = false;'
                else:                     
                    line += ' = "";'
        elif isinstance(number_of_elements, list):
            line += f' = NULL_PTR({parameter_type} **);'
        else:
            line += ' = 0;'
        
        if isinstance(number_of_elements, int):
            if number_of_elements > 1:
                line += f'\n{self.TAB}nOfElements{parameter_name} = 0;'
        elif isinstance(number_of_elements, list):
            line += f'\n{self.TAB}nOfRows{parameter_name} = 0;'
            line += f'\n{self.TAB}nOfCols{parameter_name} = 0;'

        return line 

    def _expand_parameter_info_destructor(self, parameter_name, parameter_info):
        line = ''
        parameter_name_lower_case = self._generate_lower_case_var(parameter_name)
        parameter_type = parameter_info['type']
        if parameter_type == 'enum':
            parameter_type = 'uint32'
        number_of_elements = parameter_info.get('number_of_elements', 1)
        if isinstance(number_of_elements, int):
            if number_of_elements > 1:
                line = f'\n{self.TAB}if ({parameter_name_lower_case} != NULL_PTR({parameter_type} *)) {{'
                line += f'\n{self.TAB}{self.TAB}delete[] {parameter_name_lower_case};'
                line += f'\n{self.TAB}}}'
        elif isinstance(number_of_elements, list):
            line = f'\n{self.TAB}if ({parameter_name_lower_case} != NULL_PTR({parameter_type} **)) {{'
