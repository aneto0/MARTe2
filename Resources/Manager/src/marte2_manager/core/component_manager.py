        for parameter_name in template_dict['parameters']:
            parameter = template_dict['parameters'][parameter_name]
            header_lines.append(self._expand_parameter_info_header(parameter_name, parameter))
        ok = self._replace_autogenerated_section(header_file_path, header_lines, '///AUTO-GENERATED: PARAMETERS. DO NOT EDIT!', '///AUTO-GENERATED: END OF PARAMETERS. DO NOT EDIT!')

        src_file_path = Path(self._project_path) / self._project_name / src_folder_name / comp_type_name / self._comp_name / f'{self._comp_name}.cpp'
        autogenerated_start_markers = [
            '///AUTO-GENERATED: CTOR PARAMETERS. DO NOT EDIT!',
            '///AUTO-GENERATED: DTOR PARAMETERS. DO NOT EDIT!',
            '///AUTO-GENERATED: INITIALISE PARAMETERS. DO NOT EDIT!']
        autogenerated_end_markers = [
            '///AUTO-GENERATED: END OF CTOR PARAMETERS. DO NOT EDIT!',
            '///AUTO-GENERATED: END OF DTOR PARAMETERS. DO NOT EDIT!',
            '///AUTO-GENERATED: END OF INITIALISE PARAMETERS. DO NOT EDIT!']
        expand_functions = [
            self._expand_parameter_info_constructor,
            self._expand_parameter_info_destructor,
            self._expand_parameter_info_initialise]
        for autogenerated_start_marker, autogenerated_end_marker, expand_function in zip(autogenerated_start_markers, autogenerated_end_markers, expand_functions):
            if not ok:
                break
            lines = []
            for parameter_name in template_dict['parameters']:
                parameter = template_dict['parameters'][parameter_name]
                lines.append(expand_function(parameter_name, parameter))
            lines += ['\n']
            ok = self._replace_autogenerated_section(src_file_path, lines, autogenerated_start_marker, autogenerated_end_marker)

        return ok
    
